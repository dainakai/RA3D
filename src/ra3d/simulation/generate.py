def particle_radius(p: dict[str, Any]) -> float:
    return float(p["diameter_um"]) / 2.0


def distance_um(a: dict[str, Any], b: dict[str, Any]) -> float:
    dx = float(a["x_um"]) - float(b["x_um"])
    dy = float(a["y_um"]) - float(b["y_um"])
    dz = float(a["z_um"]) - float(b["z_um"])
    return math.sqrt(dx * dx + dy * dy + dz * dz)


def overlaps_existing(candidate: dict[str, Any], active: list[dict[str, Any]], margin_um: float) -> bool:
    r = particle_radius(candidate)
    for other in active:
        if distance_um(candidate, other) < r + particle_radius(other) + margin_um:
            return True
    return False


def random_unit_vector(rng: np.random.Generator) -> np.ndarray:
    for _ in range(100):
        v = rng.normal(0.0, 1.0, size=3)
        n = float(np.linalg.norm(v))
        if n > 1e-12:
            return v / n
    return np.asarray([1.0, 0.0, 0.0], dtype=np.float64)


def particle_mass_proxy(diameter_um: float) -> float:
    return float(diameter_um) ** 3


def merged_diameter_um(d1_um: float, d2_um: float) -> float:
    return float((d1_um**3 + d2_um**3) ** (1.0 / 3.0))


def describe_optional_array(arr: np.ndarray) -> dict[str, float | int | None]:
    arr = np.asarray(arr, dtype=np.float64)
    if arr.size == 0:
        return {
            "n": 0,
            "mean": None,
            "std": None,
            "min": None,
            "p01": None,
            "p05": None,
            "p25": None,
            "p50": None,
            "p75": None,
            "p95": None,
            "p99": None,
            "max": None,
        }
    return base.describe_array(arr)


class DatasetBuilder:
    def __init__(
        self,
        project_root: Path,
        out_dir: Path,
        params: base.SynthParams,
        velocity_samples: np.ndarray,
        diameter_samples: np.ndarray,
        rng: np.random.Generator,
    ) -> None:
        self.project_root = project_root
        self.out_dir = out_dir
        self.params = params
        self.velocity_samples = velocity_samples
        self.diameter_samples = diameter_samples
        self.diameter_bin_samples = build_bin_samples(diameter_samples)
        self.rng = rng
        velocity_bound_grid = np.linspace(DIAMETER_MIN_UM, DIAMETER_MAX_UM, 4097, dtype=np.float64)
        self.max_abs_vertical_velocity_um_s = float(
            np.max(
                np.abs(
                    [
                        abs(self.base_vertical_velocity_um_s(float(diameter_um)))
                        * (
                            1.0 + SMALL_PARTICLE_Y_JITTER_MAX_ABS_FRACTION
                            if SMALL_PARTICLE_Y_JITTER_ENABLED
                            and float(diameter_um) <= SMALL_PARTICLE_Y_JITTER_MAX_DIAMETER_UM
                            else 1.0
                        )
                        for diameter_um in velocity_bound_grid
                    ]
                )
            )
        )
        self.max_boundary_flux_rate_s = (
            float(np.max(np.abs(self.velocity_samples)))
            * self.params.dx_um
            * self.params.fps
            / self.params.width_um
            + self.max_abs_vertical_velocity_um_s / self.params.height_um
        )
        self.next_particle_id = 1
        self.next_collision_event_id = 1
        self.trajectories: dict[int, dict[str, Any]] = {}
        self.collision_events: list[dict[str, Any]] = []
        self.missed_planned_events: list[dict[str, Any]] = []
        self.half_mixture_designer: half_mixture.HalfMixtureDesigner | None = None
        self.planned_parent_segments: list[dict[str, Any]] = []

    def draw_horizontal_velocity_um_s(self) -> float:
        idx = int(self.rng.integers(0, self.velocity_samples.shape[0]))
        return float(self.velocity_samples[idx] * self.params.dx_um * self.params.fps)

    def draw_diameter_um(self) -> float:
        idx = int(self.rng.integers(0, self.diameter_samples.shape[0]))
        return float(self.diameter_samples[idx])

    def draw_diameter_from_bin(self, bin_index: int) -> float:
        return sample_diameter_from_bin(bin_index, self.diameter_bin_samples, self.rng)

    def base_vertical_velocity_um_s(self, diameter_um: float) -> float:
        return base.terminal_velocity_beard_1976_um_s(diameter_um) + Y_VELOCITY_OFFSET_UM_S

    def draw_vertical_velocity_um_s(self, diameter_um: float) -> float:
        baseline = self.base_vertical_velocity_um_s(diameter_um)
        if not SMALL_PARTICLE_Y_JITTER_ENABLED or diameter_um > SMALL_PARTICLE_Y_JITTER_MAX_DIAMETER_UM:
            return baseline
        for _ in range(10000):
            relative_change = float(self.rng.normal(0.0, SMALL_PARTICLE_Y_JITTER_STD_FRACTION))
            if (
                -SMALL_PARTICLE_Y_JITTER_MAX_ABS_FRACTION
                <= relative_change
                <= SMALL_PARTICLE_Y_JITTER_MAX_ABS_FRACTION
            ):
                return baseline * (1.0 + relative_change)
        raise RuntimeError("Could not sample a truncated Gaussian Y-velocity change")

    def create_particle(
        self,
        frame: int,
        x_um: float,
        y_um: float,
        z_um: float,
        diameter_um: float,
        vx_um_s: float,
        vy_um_s: float,
        vz_um_s: float,
        birth_reason: str,
        entry_face: str,
        parent1_id: int | None = None,
        parent2_id: int | None = None,
        planned_event_id: int | None = None,
        planned_collision_frame: int | None = None,
        planned_parent_slot: int | None = None,
    ) -> dict[str, Any]:
        particle_id = self.next_particle_id
        self.next_particle_id += 1
        p = {
            "particle_id": particle_id,
            "x_um": float(x_um),
            "y_um": float(y_um),
            "z_um": float(z_um),
            "diameter_um": float(diameter_um),
            "vx_um_s": float(vx_um_s),
            "vy_um_s": float(vy_um_s),
            "vz_um_s": float(vz_um_s),
            "birth_frame": int(frame),
            "birth_reason": birth_reason,
            "entry_face": entry_face,
            "spawn_outside_volume": 0,
            "has_entered_propagation": 0,
            "parent1_id": parent1_id,
            "parent2_id": parent2_id,
            "planned_event_id": planned_event_id,
            "planned_collision_frame": planned_collision_frame,
            "planned_parent_slot": planned_parent_slot,
        }
        self.trajectories[particle_id] = {
            "particle_id": particle_id,
            "birth_frame": int(frame),
            "death_frame": "",
            "birth_reason": birth_reason,
            "death_reason": "",
            "parent1_id": parent1_id if parent1_id is not None else "",
            "parent2_id": parent2_id if parent2_id is not None else "",
            "planned_event_id": planned_event_id if planned_event_id is not None else "",
            "planned_collision_frame": planned_collision_frame if planned_collision_frame is not None else "",
            "initial_x_um": float(x_um),
            "initial_y_um": float(y_um),
            "initial_z_um": float(z_um),
            "initial_diameter_um": float(diameter_um),
            "initial_vx_um_s": float(vx_um_s),
            "initial_vy_um_s": float(vy_um_s),
            "initial_vz_um_s": float(vz_um_s),
            "final_x_um": "",
            "final_y_um": "",
            "final_z_um": "",
            "final_diameter_um": "",
        }
        return p

    def end_particle(self, p: dict[str, Any], frame: int, reason: str) -> None:
        particle_id = int(p["particle_id"])
        rec = self.trajectories.get(particle_id)
        if rec is None or rec["death_frame"] != "":
            return
        rec["death_frame"] = int(frame)
        rec["death_reason"] = reason
        rec["final_x_um"] = float(p["x_um"])
        rec["final_y_um"] = float(p["y_um"])
        rec["final_z_um"] = float(p["z_um"])
        rec["final_diameter_um"] = float(p["diameter_um"])

    def make_uniform_initial_particle(self, frame: int, active: list[dict[str, Any]]) -> dict[str, Any]:
        for _ in range(500):
            x = float(self.rng.uniform(0.0, self.params.width_um))
            y = float(self.rng.uniform(0.0, self.params.height_um))
            z = float(self.rng.uniform(0.0, self.params.depth_um))
            safe_particle: dict[str, float] | None = None
            for _ in range(2000):
                d = self.draw_diameter_um()
                vx = self.draw_horizontal_velocity_um_s()
                vy = self.draw_vertical_velocity_um_s(d)
                vz = self.draw_horizontal_velocity_um_s()
                candidate = {
                    "x_um": x,
                    "y_um": y,
                    "z_um": z,
                    "diameter_um": d,
                    "vx_um_s": vx,
                    "vy_um_s": vy,
                    "vz_um_s": vz,
                }
                future = {
                    **candidate,
                    "x_um": x + vx / self.params.fps * INITIAL_MIN_NOMINAL_RESIDENCE_FRAMES,
                    "y_um": y + vy / self.params.fps * INITIAL_MIN_NOMINAL_RESIDENCE_FRAMES,
                    "z_um": z + vz / self.params.fps * INITIAL_MIN_NOMINAL_RESIDENCE_FRAMES,
                }
                if not inside_volume(future, self.params):
                    continue
                if overlaps_existing(candidate, active, 5.0):
                    continue
                if not z_safe_during_xy_residence(candidate, frame, self.params):
                    continue
                safe_particle = candidate
                break
            if safe_particle is None:
                continue
            p = self.create_particle(
                frame=frame,
                x_um=x,
                y_um=y,
                z_um=z,
                diameter_um=float(safe_particle["diameter_um"]),
                vx_um_s=float(safe_particle["vx_um_s"]),
                vy_um_s=float(safe_particle["vy_um_s"]),
                vz_um_s=float(safe_particle["vz_um_s"]),
                birth_reason="initial",
                entry_face="initial_uniform_nominal_volume",
            )
            p["has_entered_propagation"] = 1
            return p
        raise RuntimeError(
            "Could not place a non-overlapping uniform initial particle with a Z-safe trajectory"
        )

    def make_random_particle(self, frame: int, active: list[dict[str, Any]], reason: str) -> dict[str, Any]:
        for _ in range(5000):
            d = self.draw_diameter_um()
            vx = self.draw_horizontal_velocity_um_s()
            vy = self.draw_vertical_velocity_um_s(d)
            vz = self.draw_horizontal_velocity_um_s()
            x_flux_rate = abs(vx) / self.params.width_um
            y_flux_rate = abs(vy) / self.params.height_um
            total_flux_rate = x_flux_rate + y_flux_rate
            if self.rng.random() > total_flux_rate / self.max_boundary_flux_rate_s:
                continue
            x_step = vx / self.params.fps
            y_step = vy / self.params.fps
            z_step = vz / self.params.fps
            z = float(
                self.rng.uniform(
                    Z_BOUNDARY_SAFETY_MARGIN_UM, self.params.depth_um - Z_BOUNDARY_SAFETY_MARGIN_UM
                )
            )
            if self.rng.random() * total_flux_rate < x_flux_rate:
                y_low = max(0.0, -y_step)
                y_high = self.params.height_um - max(0.0, y_step)
                if y_low >= y_high or abs(x_step) <= 1e-12:
                    continue
                y = float(self.rng.uniform(y_low, y_high))
                if vx >= 0.0:
                    x = -float(self.rng.uniform(0.05, 0.95) * abs(x_step))
                    entry_face = "x_min"
                else:
                    x = self.params.width_um + float(self.rng.uniform(0.05, 0.95) * abs(x_step))
                    entry_face = "x_max"
            else:
                x_low = max(0.0, -x_step)
                x_high = self.params.width_um - max(0.0, x_step)
                if x_low >= x_high or abs(y_step) <= 1e-12:
                    continue
                x = float(self.rng.uniform(x_low, x_high))
                if vy >= 0.0:
                    y = -float(self.rng.uniform(0.05, 0.95) * abs(y_step))
                    entry_face = "y_min"
                else:
                    y = self.params.height_um + float(self.rng.uniform(0.05, 0.95) * abs(y_step))
                    entry_face = "y_max"
            activation = {
                "x_um": x,
                "y_um": y,
                "z_um": z,
                "diameter_um": d,
                "vx_um_s": vx,
                "vy_um_s": vy,
                "vz_um_s": vz,
            }
            birth = backtrace_to_outside_propagation(activation, frame, self.params)
            if birth is None or birth[0] < 0:
                continue
            (birth_frame, birth_x, birth_y, birth_z) = birth
            p = self.create_particle(
                frame=birth_frame,
                x_um=birth_x,
                y_um=birth_y,
                z_um=birth_z,
                diameter_um=d,
                vx_um_s=vx,
                vy_um_s=vy,
                vz_um_s=vz,
                birth_reason=reason,
                entry_face=entry_face,
            )
            p["spawn_outside_volume"] = 1
            if not outside_propagation_xy(p, self.params):
                self.trajectories.pop(int(p["particle_id"]), None)
                self.next_particle_id -= 1
                continue
            if not z_safe_during_xy_residence(p, birth_frame, self.params):
                self.trajectories.pop(int(p["particle_id"]), None)
                self.next_particle_id -= 1
                continue
            p["x_um"] = x
            p["y_um"] = y
            p["z_um"] = z
            p["activation_frame"] = frame
            p["has_entered_propagation"] = 1
            if not incoming_next_frame(p, self.params):
                self.trajectories.pop(int(p["particle_id"]), None)
                self.next_particle_id -= 1
                continue
            next_p = {**p, "x_um": x + x_step, "y_um": y + y_step, "z_um": z + z_step}
            if overlaps_existing(next_p, active, 5.0):
                self.trajectories.pop(int(p["particle_id"]), None)
                self.next_particle_id -= 1
                continue
            return p
        raise RuntimeError(f"Could not place random particle for reason={reason!r}")

