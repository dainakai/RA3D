def finite_float(value: Any, default: float | None = None) -> float | None:
    try:
        out = float(value)
    except (TypeError, ValueError):
        return default
    return out if math.isfinite(out) else default


def collect_x_velocity_samples(smoothed_dirs: list[Path], sample_size: int, seed: int) -> np.ndarray:
    rng = random.Random(seed)
    sample: list[float] = []
    n = 0
    for smoothed_dir in smoothed_dirs:
        for path in sorted(smoothed_dir.glob("path_*.csv")):
            with path.open(newline="") as f:
                reader = csv.DictReader(f)
                for row in reader:
                    vx_px_frame = finite_float(row.get("vx"))
                    post = finite_float(row.get("postOutProb"), 0.0)
                    if vx_px_frame is None or post is None or post > 0.5:
                        continue
                    n += 1
                    if len(sample) < sample_size:
                        sample.append(vx_px_frame)
                    else:
                        j = rng.randrange(n)
                        if j < sample_size:
                            sample[j] = vx_px_frame
    if not sample:
        raise RuntimeError(f"No x velocity samples collected from {smoothed_dirs}")
    return np.asarray(sample, dtype=np.float64)


def prepare_velocity_samples(
    project_root: Path,
    out_dir: Path,
    params: base.SynthParams,
    refresh: bool,
    source_glob: str | None,
    quantiles_csv: Path | None,
) -> tuple[np.ndarray, dict[str, object]]:
    metadata_dir = out_dir / "metadata"
    metadata_dir.mkdir(parents=True, exist_ok=True)
    vx_path = metadata_dir / "source_x_velocity_px_frame_sample.npy"
    summary_path = metadata_dir / "source_distribution_summary.json"
    if not refresh and vx_path.exists() and summary_path.exists():
        samples = np.load(vx_path)
        summary = json.loads(summary_path.read_text(encoding="utf-8"))
        return (samples, summary)
    if quantiles_csv is not None:
        quantiles: list[float] = []
        values: list[float] = []
        with quantiles_csv.open(newline="") as f:
            for row in csv.DictReader(f):
                q = finite_float(row.get("quantile"))
                value = finite_float(row.get("vx_px_per_frame"))
                if q is None or value is None:
                    continue
                quantiles.append(q)
                values.append(value)
        q_arr = np.asarray(quantiles, dtype=np.float64)
        value_arr = np.asarray(values, dtype=np.float64)
        if q_arr.size < 2 or q_arr[0] != 0.0 or q_arr[-1] != 1.0 or np.any(np.diff(q_arr) <= 0.0):
            raise RuntimeError(f"{quantiles_csv} must contain strictly increasing quantiles from 0 to 1")
        sample_rng = np.random.default_rng(params.seed + 113)
        samples = np.interp(sample_rng.random(SOURCE_SAMPLE_SIZE), q_arr, value_arr)
        source_note: str | list[str] = str(quantiles_csv)
    elif source_glob:
        source_dirs = sorted((path for path in project_root.glob(source_glob) if path.is_dir()))
        if not source_dirs:
            raise RuntimeError(f"No velocity source directories matched {source_glob!r} below {project_root}")
        samples = collect_x_velocity_samples(source_dirs, SOURCE_SAMPLE_SIZE, params.seed + 113)
        source_note: str | list[str] = [str(path) for path in source_dirs]
    else:
        raise RuntimeError(
            "Specify --velocity-quantiles-csv for bundled reproduction or --velocity-source-glob to rebuild the table from experimental tracks"
        )
    np.save(vx_path, samples)
    summary = {
        "source": {
            "velocity_dir_or_cache": source_note,
            "velocity_column": "vx",
            "velocity_policy": "x and z horizontal velocities are sampled independently from the 260715 empirical vx inverse-CDF table"
            if quantiles_csv is not None
            else "x and z horizontal velocities draw independently from the empirical x velocity sample",
        },
        "cached_samples": {"x_velocity_px_frame_npy": str(vx_path), "sample_size_limit": SOURCE_SAMPLE_SIZE},
        "vx_px_per_frame": base.describe_array(samples),
        "vz_equivalent_px_per_frame": base.describe_array(samples),
    }
    summary_path.write_text(json.dumps(summary, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return (samples, summary)


def prepare_diameter_samples(
    project_root: Path, out_dir: Path, refresh: bool, density_csv: Path | None, seed: int
) -> tuple[np.ndarray, dict[str, object]]:
    metadata_dir = out_dir / "metadata"
    metadata_dir.mkdir(parents=True, exist_ok=True)
    diam_path = metadata_dir / "source_diameter_um_sample.npy"
    if not refresh and diam_path.exists():
        samples = np.load(diam_path)
        source_note = str(density_csv) if density_csv is not None else str(diam_path)
        weights_path = metadata_dir / "source_diameter_number_density_weights.csv"
        if density_csv is not None and weights_path.exists():
            with weights_path.open(newline="") as f:
                density_rows = list(csv.DictReader(f))
        else:
            density_rows = []
    elif density_csv is not None:
        grouped: dict[tuple[float, float], list[float]] = defaultdict(list)
        prepared_rows: list[dict[str, float | int]] = []
        with density_csv.open(newline="") as f:
            for row in csv.DictReader(f):
                lo = finite_float(row.get("diameter_bin_low_um"))
                hi = finite_float(row.get("diameter_bin_high_um"))
                density = finite_float(row.get("number_density_bin_cm3"))
                probability = finite_float(row.get("relative_probability"))
                if lo is None or hi is None:
                    continue
                if lo < DIAMETER_MIN_UM or hi > DIAMETER_MAX_UM:
                    continue
                if probability is not None and probability >= 0.0:
                    prepared_rows.append(
                        {
                            "diameter_bin_low_um": lo,
                            "diameter_bin_high_um": hi,
                            "scene_count": int(float(row.get("scene_count", 14))),
                            "scene_mean_number_density_bin_cm3": float(
                                row.get("scene_mean_number_density_bin_cm3", 0.0)
                            ),
                            "relative_probability": probability,
                        }
                    )
                elif density is not None and density >= 0.0:
                    grouped[lo, hi].append(density)
        if not grouped and (not prepared_rows):
            raise RuntimeError(
                f"No diameter-density rows remained in {density_csv} for {DIAMETER_MIN_UM:g}-{DIAMETER_MAX_UM:g} um"
            )
        if prepared_rows:
            density_rows = sorted(prepared_rows, key=lambda row: float(row["diameter_bin_low_um"]))
            weights = np.asarray(
                [float(row["relative_probability"]) for row in density_rows], dtype=np.float64
            )
        else:
            density_rows = []
            for (lo, hi), values in sorted(grouped.items()):
                density_rows.append(
                    {
                        "diameter_bin_low_um": lo,
                        "diameter_bin_high_um": hi,
                        "scene_count": len(values),
                        "scene_mean_number_density_bin_cm3": float(np.mean(values)),
                    }
                )
            weights = np.asarray(
                [float(row["scene_mean_number_density_bin_cm3"]) for row in density_rows], dtype=np.float64
            )
        weights /= float(weights.sum())
        sample_rng = np.random.default_rng(seed + 197)
        choices = sample_rng.choice(len(density_rows), size=SOURCE_SAMPLE_SIZE, p=weights)
        lows = np.asarray(
            [float(density_rows[int(index)]["diameter_bin_low_um"]) for index in choices], dtype=np.float64
        )
        highs = np.asarray(
            [float(density_rows[int(index)]["diameter_bin_high_um"]) for index in choices], dtype=np.float64
        )
        samples = sample_rng.uniform(lows, highs)
        np.save(diam_path, samples)
        for density_row, probability in zip(density_rows, weights, strict=True):
            density_row["relative_probability"] = float(probability)
        weights_path = metadata_dir / "source_diameter_number_density_weights.csv"
        with weights_path.open("w", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=list(density_rows[0]))
            writer.writeheader()
            writer.writerows(density_rows)
        source_note = str(density_csv)
    else:
        raise RuntimeError("Specify --diameter-density-csv with the bundled 260715 distribution")
    if samples.size == 0:
        raise RuntimeError(
            f"Diameter sample is empty after {DIAMETER_MIN_UM:g}-{DIAMETER_MAX_UM:g} um filtering"
        )
    summary = {
        "source_diameter_sample_npy": source_note,
        "diameter_policy": f"relative distribution from the across-scene mean of {density_csv}, sampled uniformly within each source bin"
        if density_csv is not None
        else f"diameter distribution limited to {DIAMETER_MIN_UM:g}-{DIAMETER_MAX_UM:g} um",
        "diameter_density_bin_count": len(density_rows),
        "diameter_um": base.describe_array(samples),
    }
    return (samples.astype(np.float64), summary)


def diameter_bins() -> list[tuple[int, float, float]]:
    bins: list[tuple[int, float, float]] = []
    idx = 0
    lo = DIAMETER_MIN_UM
    while lo < DIAMETER_MAX_UM:
        hi = min(lo + DIAMETER_BIN_WIDTH_UM, DIAMETER_MAX_UM)
        bins.append((idx, lo, hi))
        idx += 1
        lo = hi
    return bins


def bin_index_for_diameter(diameter_um: float) -> int:
    idx = int(math.floor((diameter_um - DIAMETER_MIN_UM) / DIAMETER_BIN_WIDTH_UM))
    return max(0, min(idx, len(diameter_bins()) - 1))


def sample_diameter_from_bin(
    bin_index: int, bin_samples: dict[int, np.ndarray], rng: np.random.Generator
) -> float:
    samples = bin_samples[bin_index]
    return float(samples[int(rng.integers(0, samples.shape[0]))])


def inside_volume(p: dict[str, Any], params: base.SynthParams) -> bool:
    return (
        0.0 <= float(p["x_um"]) < params.width_um
        and 0.0 <= float(p["y_um"]) < params.height_um
        and (0.0 <= float(p["z_um"]) < params.depth_um)
    )


def incoming_next_frame(p: dict[str, Any], params: base.SynthParams) -> bool:
    if inside_volume(p, params):
        return False
    dt = 1.0 / params.fps
    next_p = {
        "x_um": float(p["x_um"]) + float(p["vx_um_s"]) * dt,
        "y_um": float(p["y_um"]) + float(p["vy_um_s"]) * dt,
        "z_um": float(p["z_um"]) + float(p["vz_um_s"]) * dt,
    }
    return inside_volume(next_p, params)


def inside_next_frame(p: dict[str, Any], params: base.SynthParams) -> bool:
    dt = 1.0 / params.fps
    next_p = {
        "x_um": float(p["x_um"]) + float(p["vx_um_s"]) * dt,
        "y_um": float(p["y_um"]) + float(p["vy_um_s"]) * dt,
        "z_um": float(p["z_um"]) + float(p["vz_um_s"]) * dt,
    }
    return inside_volume(next_p, params)


def supply_particle(p: dict[str, Any], params: base.SynthParams) -> bool:
    return inside_volume(p, params) or incoming_next_frame(p, params)


def propagation_margin_um(params: base.SynthParams) -> float:
    return PROPAGATION_MARGIN_PX * params.dx_um


def inside_propagation_xy(p: dict[str, Any], params: base.SynthParams) -> bool:
    margin_um = propagation_margin_um(params)
    return (
        -margin_um <= float(p["x_um"]) < params.width_um + margin_um
        and -margin_um <= float(p["y_um"]) < params.height_um + margin_um
    )


def inside_propagation_domain(p: dict[str, Any], params: base.SynthParams) -> bool:
    return inside_propagation_xy(p, params) and 0.0 <= float(p["z_um"]) < params.depth_um


def axis_inside_step_interval(
    position: float, step: float, lower: float, upper: float, max_step: int | None
) -> tuple[int, int | float] | None:
    """Return integer steps whose linearly advected coordinate is in [lower, upper)."""
    if max_step is not None and max_step < 0:
        return None
    if step > 0.0:
        first = math.ceil((lower - position) / step)
        last = math.ceil((upper - position) / step) - 1
    elif step < 0.0:
        first = math.floor((upper - position) / step) + 1
        last = math.floor((lower - position) / step)
    elif lower <= position < upper:
        (first, last) = (0, max_step if max_step is not None else math.inf)
    else:
        return None
    first = max(0, int(first))
    if max_step is not None:
        last = min(max_step, int(last))
    return (first, last) if first <= last else None


def xy_propagation_step_interval(
    p: dict[str, Any], frame: int, params: base.SynthParams
) -> tuple[int, int | float] | None:
    """Return the complete future interval spent inside the XY propagation plane."""
    del frame
    margin_um = propagation_margin_um(params)
    x_interval = axis_inside_step_interval(
        float(p["x_um"]), float(p["vx_um_s"]) / params.fps, -margin_um, params.width_um + margin_um, None
    )
    y_interval = axis_inside_step_interval(
        float(p["y_um"]), float(p["vy_um_s"]) / params.fps, -margin_um, params.height_um + margin_um, None
    )
    if x_interval is None or y_interval is None:
        return None
    first = max(x_interval[0], y_interval[0])
    last = min(x_interval[1], y_interval[1])
    return (first, last) if first <= last else None


def z_safe_during_xy_residence(p: dict[str, Any], frame: int, params: base.SynthParams) -> bool:
    """Check that Z remains in range at every frame whose XY center is renderable."""
    interval = xy_propagation_step_interval(p, frame, params)
    if interval is None:
        return True
    z_step = float(p["vz_um_s"]) / params.fps
    z_first = float(p["z_um"]) + z_step * interval[0]
    if math.isinf(interval[1]):
        return (
            abs(z_step) <= 1e-15
            and Z_BOUNDARY_SAFETY_MARGIN_UM <= z_first < params.depth_um - Z_BOUNDARY_SAFETY_MARGIN_UM
        )
    z_last = float(p["z_um"]) + z_step * interval[1]
    z_min = min(z_first, z_last)
    z_max = max(z_first, z_last)
    return z_min >= Z_BOUNDARY_SAFETY_MARGIN_UM and z_max < params.depth_um - Z_BOUNDARY_SAFETY_MARGIN_UM


def z_path_inside(
    start_z_um: float, vz_um_s: float, step_start: int, step_end: int, params: base.SynthParams
) -> bool:
    """Check a linear Z path over an inclusive integer-step interval."""
    z_step = vz_um_s / params.fps
    z0 = start_z_um + z_step * step_start
    z1 = start_z_um + z_step * step_end
    return (
        min(z0, z1) >= Z_BOUNDARY_SAFETY_MARGIN_UM
        and max(z0, z1) < params.depth_um - Z_BOUNDARY_SAFETY_MARGIN_UM
    )


def inside_next_propagation_domain(p: dict[str, Any], params: base.SynthParams) -> bool:
    dt = 1.0 / params.fps
    next_p = {
        "x_um": float(p["x_um"]) + float(p["vx_um_s"]) * dt,
        "y_um": float(p["y_um"]) + float(p["vy_um_s"]) * dt,
        "z_um": float(p["z_um"]) + float(p["vz_um_s"]) * dt,
    }
    return inside_propagation_domain(next_p, params)


def outside_propagation_xy(p: dict[str, Any], params: base.SynthParams) -> bool:
    return not inside_propagation_xy(p, params)


def backtrace_to_outside_propagation(
    p: dict[str, Any], activation_frame: int, params: base.SynthParams
) -> tuple[int, float, float, float] | None:
    """Backtrace an inflowing particle to its first frame beyond the propagation plane."""
    dt = 1.0 / params.fps
    for steps in range(1, 10001):
        x_um = float(p["x_um"]) - float(p["vx_um_s"]) * dt * steps
        y_um = float(p["y_um"]) - float(p["vy_um_s"]) * dt * steps
        z_um = float(p["z_um"]) - float(p["vz_um_s"]) * dt * steps
        candidate = {"x_um": x_um, "y_um": y_um}
        if outside_propagation_xy(candidate, params):
            return (activation_frame - steps, x_um, y_um, z_um)
    return None


def hologram_renderable_particle(p: dict[str, Any], params: base.SynthParams) -> bool:
    return inside_propagation_domain(p, params)


def renderable_or_supply_particle(p: dict[str, Any], params: base.SynthParams) -> bool:
    return inside_propagation_domain(p, params) or inside_next_propagation_domain(p, params)


